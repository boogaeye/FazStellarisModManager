using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using FazStellarisModmanager.Core.Descriptors;

namespace FazStellarisModmanager.Core.Addons;

/// <summary>
/// Builds Faz Addons from the settings and the current game (<see cref="MarketCatalog"/>, which holds the winning files' bytes, and
/// <see cref="TechAddonCatalog"/>, which custom techs are checked against). Pure and deterministic: the same catalogs and settings give the
/// same bytes, whatever order the settings' maps enumerate in. Writes nothing; see <see cref="AddonMod.Write"/>.
/// </summary>
public static class AddonBuilder
{
    public const string DescriptorPath = "descriptor.mod";
    public const string ReadmePath = "README.txt";
    public const string DefinesPath = "common/defines/zzzzz_faz_addons.txt";
    public const string MarketEventsPath = "events/faz_addons_market.txt";
    public const string MarketOnActionsPath = "common/on_actions/zzzzz_faz_addons.txt";
    public const string TechPath = "common/technology/zzzzz_faz_addons_tech.txt";
    public const string TechLocalisationPath = "localisation/english/faz_addons_l_english.yml";
    const string LocalisationHeader = "l_english:";

    static readonly string Lf = ((char)10).ToString();
    static readonly string Tab = ((char)9).ToString();
    static readonly string Quote = ((char)34).ToString();

    static readonly string Readme =
        "Faz Addons is generated by Faz Stellaris Mod Manager and loads after every mod." + Lf
        + "Apply on the Addons tab rebuilds it, so changes made here are overwritten." + Lf;

    static readonly UTF8Encoding StrictUtf8 = new(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true);
    static readonly byte[] Bom = [0xEF, 0xBB, 0xBF];

    /// <summary>
    /// The mod's files. Marketplace settings are first normalized against <paramref name="catalog"/>, so values equal to the game's change
    /// nothing, and overrides of resources the catalog doesn't have are ignored. Each winning common/strategic_resources file holding a changed
    /// resource is output under its own path: its original bytes with only those values edited (BOM and line endings kept). Changed market
    /// rules and AI lists go to <see cref="DefinesPath"/>. The custom techs without errors against <paramref name="techs"/> (see
    /// <see cref="TechValidator.Buildable"/>) go to <see cref="TechPath"/> and <see cref="TechLocalisationPath"/>, in settings order;
    /// <see cref="TechAddonCatalog.Empty"/> will do while Technologies is off. <paramref name="gameVersion"/> (e.g. "Cepheus v4.5.2") sets
    /// the descriptor's supported_version.
    /// </summary>
    public static AddonOutput Build(MarketCatalog catalog, TechAddonCatalog techs, AddonSettings settings, string? gameVersion)
    {
        var files = new List<(string Path, byte[] Bytes)>();
        if (settings.Enabled && settings.Marketplace is { Enabled: true } marketplace)
        {
            var market = marketplace.Normalize(catalog);
            files.AddRange(ResourceFiles(catalog, market));
            if (DefinesFile(catalog, market) is { } defines) files.Add((DefinesPath, defines));
            files.AddRange(GalacticMarketFiles(catalog, market));
        }
        if (settings.Enabled && settings.Technologies is { Enabled: true, Techs: { Count: > 0 } custom }
            && TechValidator.Buildable(custom, techs) is { Count: > 0 } buildable)
        {
            files.Add((TechPath, Encoding.UTF8.GetBytes(string.Join(Lf, buildable.Select(t => TechBlock(t, techs))))));
            files.Add((TechLocalisationPath, [.. Bom, .. Encoding.UTF8.GetBytes(LocalisationHeader + Lf + string.Concat(buildable.Select(TechLocalisation)))]));
        }
        var hasChanges = files.Count > 0;
        files.Add((DescriptorPath, Encoding.UTF8.GetBytes(Descriptor(gameVersion))));
        files.Add((ReadmePath, hasChanges ? Encoding.UTF8.GetBytes(Readme) : []));
        return new AddonOutput(files.OrderBy(f => f.Path, StringComparer.Ordinal).ToList(), hasChanges);
    }

    // Strategic resources can't be overridden one definition at a time, so each file with a changed resource is shipped whole under the same
    // name (loading after the original replaces it), edited in place.
    static IEnumerable<(string Path, byte[] Bytes)> ResourceFiles(MarketCatalog catalog, MarketplaceSettings market)
    {
        foreach (var file in catalog.Files)
        {
            var edits = file.Keys
                .Select(key => (Key: key, Values: Values(catalog.Find(key)!, market.Resources?.GetValueOrDefault(key))))
                .Where(e => e.Values.Count > 0)
                .ToList();
            if (edits.Count == 0) continue;

            var (bom, encoding, text) = Decode(file.Bytes);
            foreach (var (key, values) in edits)
                foreach (var (name, value) in values)
                    text = ScriptTextEditor.SetValue(text, key, name, value);
            byte[] bytes = bom ? [.. Bom, .. encoding.GetBytes(text)] : encoding.GetBytes(text);
            if (!bytes.AsSpan().SequenceEqual(file.Bytes)) yield return (file.Path, bytes);
        }
    }

    // The values to set in a resource's block. They are listed in reverse because each missing key is inserted right after the '{', so the
    // inserted lines read market_amount, market_price, tradable, max.
    static List<(string Name, string Value)> Values(ResourceInfo resource, ResourceOverride? o)
    {
        var values = new List<(string Name, string Value)>();
        if (o is null) return values;
        if (o.OnMarket == true)
        {
            values.Add(("market_amount", Int(o.MarketAmount ?? (resource.MarketAmount > 0 ? resource.MarketAmount : MarketCatalog.SuggestedBundle(resource.Category)))));
            values.Add(("market_price", Int(o.MarketPrice ?? (resource.MarketPrice > 0 ? resource.MarketPrice : MarketCatalog.SuggestedPrice))));
        }
        else if (o.OnMarket == false)
        {
            values.Add(("market_amount", "-1"));
        }
        else
        {
            if (o.MarketAmount is { } amount) values.Add(("market_amount", Int(amount)));
            if (o.MarketPrice is { } price) values.Add(("market_price", Int(price)));
        }
        if (o.Tradable is { } tradable) values.Add(("tradable", tradable ? "yes" : "no"));
        if (o.BaseStorage is { } storage && resource.Max is not null && !resource.FixedMax) values.Add(("max", Int(storage)));
        values.Reverse();
        return values;
    }

    // Defines override per key, so only the changed ones are written, in a fixed order. The AI lists are written whole: the current list
    // without the resources taken out, then the ones added (ordinal order).
    static byte[]? DefinesFile(MarketCatalog catalog, MarketplaceSettings market)
    {
        var blocks = new List<string>();

        var economy = new List<string>();
        if (market.MaxBaseAmounts is { } maxBase) economy.Add("MARKET_MAX_BASE_AMOUNTS = " + Int(maxBase));
        if (market.TradeFeeBase is { } feeBase) economy.Add("MARKET_TRADE_FEE_BASE = " + Number(feeBase));
        if (market.TradeFeeMin is { } feeMin) economy.Add("MARKET_TRADE_FEE_MIN = " + Number(feeMin));
        if (market.MinFluctuation is { } minSwing) economy.Add("MARKET_MIN_FLUCTUATION_FROM_BASE_PRICE = " + Int(minSwing));
        if (market.MaxFluctuation is { } maxSwing) economy.Add("MARKET_MAX_FLUCTUATION_FROM_BASE_PRICE = " + Int(maxSwing));
        if (economy.Count > 0) blocks.Add(Block("NEconomy", economy));

        var ai = catalog.Resources
            .Select(r => (r.Key, Trades: market.Resources?.GetValueOrDefault(r.Key)?.AiTrades))
            .Where(x => x.Trades is not null)
            .ToList();
        if (ai.Count > 0)
        {
            var removed = ai.Where(x => x.Trades == false).Select(x => x.Key).ToHashSet(StringComparer.OrdinalIgnoreCase);
            var added = ai.Where(x => x.Trades == true).Select(x => x.Key).Order(StringComparer.Ordinal).ToList();
            string List(string name, IReadOnlyList<string> current)
            {
                var items = current.Where(k => !removed.Contains(k)).Concat(added.Where(k => !current.Contains(k, StringComparer.OrdinalIgnoreCase))).ToList();
                return name + " = {" + string.Concat(items.Select(k => " " + Quote + k + Quote)) + " }";
            }
            blocks.Add(Block("NAI", [List("AI_ALLOWED_TO_BUY", catalog.AiAllowedToBuy), List("AI_ALLOWED_TO_SELL", catalog.AiAllowedToSell)]));
        }

        return blocks.Count == 0 ? null : Encoding.UTF8.GetBytes(string.Join(Lf, blocks));
    }

    // The Galactic Market keeps its own list of traded resources in the save: the game adds its resources with enable_on_market when the
    // market is founded and from a monthly event (action.116), never modded ones. A monthly event does the same for every resource the
    // settings put on the market (after normalization, OnMarket = true only remains for resources that were off it).
    static IEnumerable<(string Path, byte[] Bytes)> GalacticMarketFiles(MarketCatalog catalog, MarketplaceSettings market)
    {
        var added = catalog.Resources
            .Where(r => market.Resources?.GetValueOrDefault(r.Key)?.OnMarket == true)
            .Select(r => r.Key)
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToList();
        if (added.Count == 0) yield break;

        string T(int n) => string.Concat(Enumerable.Repeat(Tab, n));
        var events = "namespace = faz_addons" + Lf + Lf
            + "# Generated by Faz Stellaris Mod Manager. The game only puts its own resources on the Galactic Market (when it is founded," + Lf
            + "# then monthly), so this does the same for the resources Faz Addons put on the market." + Lf
            + "event = {" + Lf
            + T(1) + "id = faz_addons.1" + Lf
            + T(1) + "hide_window = yes" + Lf
            + T(1) + "is_triggered_only = yes" + Lf + Lf
            + T(1) + "trigger = {" + Lf
            + T(2) + "has_global_flag = galactic_market_founded" + Lf
            + T(2) + "OR = {" + Lf
            + string.Concat(added.Select(k => T(3) + "NOT = { is_on_market = " + k + " }" + Lf))
            + T(2) + "}" + Lf
            + T(1) + "}" + Lf + Lf
            + T(1) + "immediate = {" + Lf
            + string.Concat(added.Select(k => T(2) + "if = { limit = { NOT = { is_on_market = " + k + " } } enable_on_market = " + k + " }" + Lf))
            + T(1) + "}" + Lf
            + "}" + Lf;
        yield return (MarketEventsPath, Encoding.UTF8.GetBytes(events));
        var onActions = "on_monthly_pulse = {" + Lf + T(1) + "events = {" + Lf + T(2) + "faz_addons.1" + Lf + T(1) + "}" + Lf + "}" + Lf;
        yield return (MarketOnActionsPath, Encoding.UTF8.GetBytes(onActions));
    }

    /// <summary>
    /// What Faz Addons writes for one custom tech, whether it has errors or not (the build leaves those out): its block of
    /// <see cref="TechPath"/>, and its localisation (<see cref="TechLocalisationPath"/>'s text for that tech alone, without the BOM).
    /// </summary>
    public static (string Technology, string Localisation) TechText(CustomTech tech, TechAddonCatalog catalog) =>
        (TechBlock(tech, catalog), LocalisationHeader + Lf + TechLocalisation(tech));

    // One tech's block: the base game's repeatable layout, with the repeatable-only lines, the rare flag, the ethics (each regular ethic with
    // its fanatic variant when the game has one) and the prerequisites only when they apply. Empty groups of lines are left out with their
    // blank line.
    static string TechBlock(CustomTech tech, TechAddonCatalog catalog)
    {
        string T(int n) => string.Concat(Enumerable.Repeat(Tab, n));

        var basics = new List<string> { "area = " + tech.Area, "tier = " + Int(tech.Tier), "category = { " + tech.Category + " }", "cost = " + Int(tech.Cost) };
        if (tech.Repeatable) basics.AddRange(["cost_per_level = " + Int(tech.CostPerLevel), "levels = -1"]);
        basics.Add("icon = " + tech.Icon);
        if (tech.Rare) basics.Add("is_rare = yes");
        basics.Add("weight = " + Int(tech.Weight));

        var conditions = new List<string>();
        if (tech.Ethics is { Count: > 0 } ethics)
        {
            var keys = ethics.SelectMany(e => catalog.FindEthic(e) is { } info ? new[] { info.Key, info.FanaticKey } : [e]).OfType<string>();
            conditions.Add("potential = {" + Lf + T(2) + "OR = {" + Lf + string.Concat(keys.Select(k => T(3) + "has_ethic = " + k + Lf)) + T(2) + "}" + Lf + T(1) + "}");
        }
        if (tech.Prerequisites is { Count: > 0 } prerequisites)
            conditions.Add("prerequisites = {" + string.Concat(prerequisites.Select(p => " " + Quote + p + Quote)) + " }");

        var weights = new List<string>();
        if (tech.Repeatable) weights.Add("weight_modifier = { factor = 0.5 }");
        weights.Add("ai_weight = { factor = 1 }");
        if (tech.Repeatable) weights.AddRange(["weight_groups = { repeatable }", "mod_weight_if_group_picked = { repeatable = 0.01 }"]);

        var effects = new List<string>();
        if (tech.Modifiers is { Count: > 0 } modifiers)
            effects.Add("modifier = {" + Lf + string.Concat(modifiers.Select(m => T(2) + m.Key + " = " + Number(m.Value) + Lf)) + T(1) + "}");

        var groups = new[] { basics, conditions, weights, effects }.Where(g => g.Count > 0)
            .Select(g => string.Concat(g.Select(line => Tab + line + Lf)));
        return tech.Key + " = {" + Lf + string.Join(Lf, groups) + "}" + Lf;
    }

    static string TechLocalisation(CustomTech tech) =>
        " " + tech.Key + ":0 " + Quote + LocText(tech.Name) + Quote + Lf
        + " " + tech.Key + "_desc:0 " + Quote + LocText(tech.Description) + Quote + Lf;

    // A localisation value is one line between quotes: line breaks become spaces (CRLF as one) and double quotes single ones.
    static string LocText(string text) =>
        text.Replace((char)13 + Lf, " ").Replace((char)13, ' ').Replace((char)10, ' ').Replace((char)34, (char)39);

    static string Block(string name, IEnumerable<string> lines) =>
        name + " = {" + Lf + string.Concat(lines.Select(line => Tab + line + Lf)) + "}" + Lf;

    static string Descriptor(string? gameVersion) =>
        new ModDescriptor(AddonMod.Name, Path: null, Archive: null, RemoteFileId: null, Version: "1", SupportedVersion: SupportedVersion(gameVersion),
            Picture: null, Tags: ["Utilities"], Dependencies: []).Serialize();

    // "Cepheus v4.5.2" -> "v4.5.*"; "*" when the version is unknown.
    static string SupportedVersion(string? gameVersion) =>
        gameVersion is not null && Regex.Match(gameVersion, "([0-9]+)[.]([0-9]+)") is { Success: true } m
            ? $"v{m.Groups[1].Value}.{m.Groups[2].Value}.*"
            : "*";

    // Valid UTF-8 round-trips exactly; anything else is read as Latin-1, which maps every byte to one char and back. The edits only touch
    // ASCII, so the bytes outside them stay the same either way.
    static (bool Bom, Encoding Encoding, string Text) Decode(byte[] bytes)
    {
        var bom = bytes.AsSpan().StartsWith(Bom);
        var body = bom ? bytes[Bom.Length..] : bytes;
        try { return (bom, StrictUtf8, StrictUtf8.GetString(body)); }
        catch (DecoderFallbackException) { return (bom, Encoding.Latin1, Encoding.Latin1.GetString(body)); }
    }

    static string Int(int value) => value.ToString(CultureInfo.InvariantCulture);

    // Invariant culture, up to 4 decimals, never "-0".
    static string Number(double value)
    {
        var rounded = Math.Round(value, 4);
        return (rounded == 0 ? 0 : rounded).ToString("0.####", CultureInfo.InvariantCulture);
    }
}
